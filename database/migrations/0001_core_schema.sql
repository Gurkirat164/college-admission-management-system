CREATE SCHEMA admission;
CREATE EXTENSION IF NOT EXISTS btree_gist;
SET search_path = admission, pg_catalog, public;

CREATE TYPE seat_cat AS ENUM ('OPEN','EWS','OBC_NCL','SC','ST');
CREATE TABLE student (
  student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text NOT NULL CHECK(length(full_name) BETWEEN 2 AND 100)
);
CREATE TABLE app_user (
  user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE CHECK(email=lower(email)),
  password_hash text NOT NULL,
  full_name text NOT NULL,
  role text NOT NULL CHECK(role IN ('STUDENT','ADMIN','ANALYST','AUDITOR')),
  student_id bigint UNIQUE REFERENCES student,
  enabled boolean NOT NULL DEFAULT true,
  CHECK ((role='STUDENT') = (student_id IS NOT NULL))
);
CREATE TABLE app_session (
  token_hash text PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES app_user,
  csrf_hash text NOT NULL,
  expires_at timestamptz NOT NULL
);
CREATE INDEX ON app_session(expires_at);
CREATE TABLE admission_cycle (
  year int PRIMARY KEY CHECK(year BETWEEN 2020 AND 2100),
  input_revision bigint NOT NULL DEFAULT 0,
  choices_locked boolean NOT NULL DEFAULT false,
  choice_deadline timestamptz NOT NULL,
  policy_version text NOT NULL DEFAULT 'academic-fixed-pools-v1'
);
CREATE TABLE application (
  student_id bigint REFERENCES student,
  year int REFERENCES admission_cycle,
  admission_category seat_cat NOT NULL DEFAULT 'OPEN',
  status text NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','SUBMITTED','VERIFIED','REJECTED','WITHDRAWN')),
  choices_locked_at timestamptz,
  review_reason text,
  PRIMARY KEY(student_id,year)
);
CREATE INDEX ON application(year,status);
CREATE TABLE exam_result (
  student_id bigint NOT NULL,
  year int NOT NULL,
  total_marks numeric NOT NULL CHECK(total_marks BETWEEN 0 AND 300),
  crl_rank int NOT NULL CHECK(crl_rank>0),
  cat_rank int CHECK(cat_rank>0),
  PRIMARY KEY(student_id,year),
  FOREIGN KEY(student_id,year) REFERENCES application,
  UNIQUE(year,crl_rank)
);
CREATE TABLE program (
  program_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institute text NOT NULL,
  code text NOT NULL,
  name text NOT NULL,
  UNIQUE(institute,code)
);
CREATE TABLE program_eligibility (
  year int REFERENCES admission_cycle,
  program_id int REFERENCES program,
  min_marks numeric NOT NULL DEFAULT 0 CHECK(min_marks BETWEEN 0 AND 300),
  PRIMARY KEY(year,program_id)
);
CREATE TABLE seat_matrix (
  year int REFERENCES admission_cycle,
  program_id int REFERENCES program,
  seat_category seat_cat,
  seats int NOT NULL CHECK(seats BETWEEN 0 AND 10000),
  PRIMARY KEY(year,program_id,seat_category)
);
CREATE TABLE choice (
  student_id bigint,
  year int,
  pref_order smallint CHECK(pref_order BETWEEN 1 AND 30),
  program_id int NOT NULL REFERENCES program,
  PRIMARY KEY(student_id,year,pref_order),
  UNIQUE(student_id,year,program_id),
  FOREIGN KEY(student_id,year) REFERENCES exam_result
);
CREATE TABLE counselling_round (
  round_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year int NOT NULL REFERENCES admission_cycle,
  round_no int NOT NULL CHECK(round_no>0),
  status text NOT NULL DEFAULT 'CHOICES_OPEN' CHECK(status IN ('CHOICES_OPEN','LOCKED','PUBLISHED','CLOSED')),
  response_deadline timestamptz NOT NULL,
  published_at timestamptz,
  published_sim_id bigint UNIQUE,
  publish_key text,
  UNIQUE(year,round_no)
);
CREATE TABLE allocation (
  round_id int REFERENCES counselling_round,
  student_id bigint REFERENCES student,
  program_id int NOT NULL REFERENCES program,
  seat_category seat_cat NOT NULL,
  pref_order int NOT NULL CHECK(pref_order>0),
  k int NOT NULL CHECK(k>0),
  rank_used int NOT NULL CHECK(rank_used>0),
  PRIMARY KEY(round_id,student_id)
);
CREATE INDEX ON allocation(round_id,program_id,seat_category,rank_used);
CREATE TABLE student_response (
  round_id int,
  student_id bigint,
  decision text NOT NULL CHECK(decision IN ('FREEZE','FLOAT','SLIDE','WITHDRAW')),
  responded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  is_default boolean NOT NULL DEFAULT false,
  PRIMARY KEY(round_id,student_id),
  FOREIGN KEY(round_id,student_id) REFERENCES allocation
);
CREATE TABLE seat_holding (
  year int,
  student_id bigint,
  program_id int NOT NULL REFERENCES program,
  seat_category seat_cat NOT NULL,
  source text NOT NULL CHECK(source IN ('ROUND','SPOT')),
  final boolean NOT NULL DEFAULT false,
  PRIMARY KEY(year,student_id),
  FOREIGN KEY(student_id,year) REFERENCES application
);
CREATE TABLE sim_input_snapshot (
  snapshot_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  year int NOT NULL REFERENCES admission_cycle,
  round_id int NOT NULL REFERENCES counselling_round,
  source_revision bigint NOT NULL,
  captured_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  policy_version text NOT NULL,
  engine_version text NOT NULL DEFAULT 'da-sql-v1',
  payload jsonb NOT NULL,
  payload_hash text NOT NULL
);
CREATE TABLE sim_run (
  sim_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  round_id int NOT NULL REFERENCES counselling_round,
  snapshot_id bigint NOT NULL REFERENCES sim_input_snapshot,
  base_sim_id bigint REFERENCES sim_run,
  run_by bigint NOT NULL REFERENCES app_user,
  scenario jsonb NOT NULL,
  label text NOT NULL,
  started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  duration_ms int NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT false,
  checks jsonb NOT NULL DEFAULT '{}',
  summary jsonb NOT NULL DEFAULT '{}'
);
ALTER TABLE counselling_round ADD FOREIGN KEY(published_sim_id) REFERENCES sim_run;
CREATE TABLE sim_result (
  sim_id bigint REFERENCES sim_run ON DELETE CASCADE,
  student_id bigint REFERENCES student,
  program_id int NOT NULL REFERENCES program,
  seat_category seat_cat NOT NULL,
  pref_order int NOT NULL,
  k int NOT NULL,
  rank_used int NOT NULL,
  PRIMARY KEY(sim_id,student_id)
);
CREATE INDEX ON sim_result(sim_id,program_id,seat_category,rank_used);
CREATE TABLE sim_student_outcome (
  sim_id bigint REFERENCES sim_run ON DELETE CASCADE,
  student_id bigint REFERENCES student,
  outcome text NOT NULL CHECK(outcome IN ('ALLOTTED','UNASSIGNED','WITHDRAWN','EXCLUDED')),
  PRIMARY KEY(sim_id,student_id)
);
CREATE TABLE sim_trace (
  sim_id bigint REFERENCES sim_run ON DELETE CASCADE,
  student_id bigint REFERENCES student,
  program_id int REFERENCES program,
  seat_category seat_cat,
  pref_order int NOT NULL,
  k int NOT NULL,
  rank_used int NOT NULL,
  closing_rank int,
  outcome text NOT NULL CHECK(outcome IN ('ALLOTTED','REJECTED_FULL','NOT_REACHED','RETAINED')),
  PRIMARY KEY(sim_id,student_id,k)
);
CREATE TABLE sim_diff (
  sim_id bigint REFERENCES sim_run ON DELETE CASCADE,
  student_id bigint REFERENCES student,
  base_program int REFERENCES program,
  sim_program int REFERENCES program,
  base_category seat_cat,
  sim_category seat_cat,
  base_k int,
  sim_k int,
  change_type text NOT NULL CHECK(change_type IN ('UNCHANGED','NEW_SEAT','LOST_SEAT','POOL_SHIFT','UPGRADED','DOWNGRADED')),
  PRIMARY KEY(sim_id,student_id)
);
CREATE INDEX ON sim_diff(sim_id,change_type);
CREATE TABLE document_submission (
  document_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  student_id bigint,
  year int,
  original_name text NOT NULL,
  storage_key text NOT NULL UNIQUE,
  mime_type text NOT NULL,
  checksum text NOT NULL,
  byte_count int NOT NULL CHECK(byte_count BETWEEN 1 AND 5242880),
  status text NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','VERIFIED','REJECTED')),
  reason text,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  FOREIGN KEY(student_id,year) REFERENCES application
);
CREATE TABLE hist_closing (
  year int NOT NULL,
  program_id int REFERENCES program,
  seat_category seat_cat,
  closing_rank int NOT NULL CHECK(closing_rank>0),
  source text NOT NULL DEFAULT 'synthetic',
  PRIMARY KEY(year,program_id,seat_category)
);
CREATE TABLE spot_pool (
  pool_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  year int,
  program_id int,
  seat_category seat_cat,
  initial_capacity int NOT NULL CHECK(initial_capacity>=0),
  seats_left int NOT NULL CHECK(seats_left>=0 AND seats_left<=initial_capacity),
  status text NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','CLOSED')),
  FOREIGN KEY(year,program_id,seat_category) REFERENCES seat_matrix,
  UNIQUE(year,program_id,seat_category)
);
CREATE TABLE spot_acceptance (
  acceptance_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  pool_id bigint NOT NULL REFERENCES spot_pool,
  student_id bigint NOT NULL,
  year int NOT NULL,
  idempotency_key text NOT NULL,
  accepted_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  FOREIGN KEY(student_id,year) REFERENCES application,
  UNIQUE(year,student_id),
  UNIQUE(student_id,idempotency_key)
);
CREATE TABLE audit_chain_head (
  singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
  last_seq bigint NOT NULL DEFAULT 0,
  last_hash text NOT NULL DEFAULT repeat('0',64)
);
INSERT INTO audit_chain_head(singleton) VALUES(true);
CREATE TABLE audit_ledger (
  seq bigint PRIMARY KEY,
  envelope jsonb NOT NULL,
  prev_hash text NOT NULL,
  hash text NOT NULL
);
CREATE TABLE seat_matrix_history (
  history_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  year int NOT NULL,
  program_id int NOT NULL,
  seat_category seat_cat NOT NULL,
  seats int NOT NULL,
  valid tstzrange NOT NULL CHECK(NOT isempty(valid)),
  EXCLUDE USING gist(year WITH =,program_id WITH =,seat_category WITH =,valid WITH &&)
);

CREATE FUNCTION current_app_user_id() RETURNS bigint LANGUAGE sql STABLE
SET search_path=pg_catalog,admission,pg_temp AS $$
  SELECT nullif(current_setting('app.user_id',true),'')::bigint
$$;
CREATE FUNCTION actor() RETURNS admission.app_user LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=pg_catalog,admission,pg_temp AS $$
DECLARE u admission.app_user;
BEGIN
  SELECT * INTO u FROM admission.app_user WHERE user_id=admission.current_app_user_id() AND enabled;
  IF u.user_id IS NULL THEN RAISE EXCEPTION 'Authentication required' USING ERRCODE='42501'; END IF;
  RETURN u;
END $$;
CREATE FUNCTION require_role(VARIADIC allowed text[]) RETURNS admission.app_user LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=pg_catalog,admission,pg_temp AS $$
DECLARE u admission.app_user := admission.actor();
BEGIN
  IF NOT u.role=ANY(allowed) THEN RAISE EXCEPTION 'This action is not permitted for your role' USING ERRCODE='42501'; END IF;
  RETURN u;
END $$;

DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['application','choice','exam_result','document_submission','allocation','student_response','seat_holding','sim_trace','sim_student_outcome'] LOOP
    EXECUTE format('ALTER TABLE admission.%I ENABLE ROW LEVEL SECURITY',t);
    EXECUTE format('CREATE POLICY own_student_rows ON admission.%I USING (student_id=(SELECT student_id FROM admission.app_user WHERE user_id=admission.current_app_user_id()))',t);
  END LOOP;
END $$;

REVOKE ALL ON ALL TABLES IN SCHEMA admission FROM PUBLIC;
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA admission FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA admission REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
